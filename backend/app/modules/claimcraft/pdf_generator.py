"""
PDF Generation Utility using ReportLab for ClaimCraft.

Generates official-style document readiness reports and checklists in PDF format.
Does not store documents permanently.
"""

import io
from typing import Any, Dict
from reportlab.lib.pagesizes import letter
from reportlab.lib import colors
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle


def generate_checklist_pdf(checklist_data: Dict[str, Any]) -> bytes:
    """
    Generate an in-memory PDF checklist summary using ReportLab.
    Returns bytes without saving to disk.
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer,
        pagesize=letter,
        rightMargin=40,
        leftMargin=40,
        topMargin=40,
        bottomMargin=40,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "DocTitle",
        parent=styles["Heading1"],
        fontSize=18,
        leading=22,
        textColor=colors.HexColor("#0f172a"),
        spaceAfter=6,
    )
    subtitle_style = ParagraphStyle(
        "DocSubtitle",
        parent=styles["Normal"],
        fontSize=11,
        leading=14,
        textColor=colors.HexColor("#475569"),
        spaceAfter=14,
    )
    section_style = ParagraphStyle(
        "SectionHeader",
        parent=styles["Heading2"],
        fontSize=13,
        leading=16,
        textColor=colors.HexColor("#16a34a"),
        spaceBefore=10,
        spaceAfter=8,
    )
    cell_style = ParagraphStyle(
        "TableCell",
        parent=styles["Normal"],
        fontSize=9,
        leading=11,
    )

    story = []

    # Title & Header
    story.append(Paragraph("NagrikLens • Civic Entitlement Readiness Report", title_style))
    story.append(Paragraph(f"Target Scheme: <b>{checklist_data.get('scheme_title', 'Scheme')}</b>", subtitle_style))
    story.append(Paragraph(f"Scheme ID: {checklist_data.get('scheme_id', '')} | Readiness: {checklist_data.get('readiness_percentage', 0)}%", subtitle_style))
    story.append(Spacer(1, 10))

    # Documents Table
    story.append(Paragraph("Required Documentation Checklist", section_style))

    table_data = [
        [
            Paragraph("<b>Document Name</b>", cell_style),
            Paragraph("<b>Type</b>", cell_style),
            Paragraph("<b>Mandatory</b>", cell_style),
            Paragraph("<b>Status</b>", cell_style),
            Paragraph("<b>Issuing Authority / Action</b>", cell_style),
        ]
    ]

    for item in checklist_data.get("required_documents", []):
        status_text = "READY" if item.get("status") == "ready" else "ACTION REQUIRED"
        authority = item.get("issuing_authority") or "On Record / Self-attested"
        mandatory_str = "Yes" if item.get("mandatory") else "Optional"

        table_data.append([
            Paragraph(item.get("name", ""), cell_style),
            Paragraph(item.get("document_type", ""), cell_style),
            Paragraph(mandatory_str, cell_style),
            Paragraph(status_text, cell_style),
            Paragraph(authority, cell_style),
        ])

    table = Table(table_data, colWidths=[140, 90, 60, 90, 150])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#f1f5f9")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.HexColor("#0f172a")),
        ("ALIGN", (0, 0), (-1, -1), "LEFT"),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("INNERGRID", (0, 0), (-1, -1), 0.5, colors.HexColor("#cbd5e1")),
        ("BOX", (0, 0), (-1, -1), 1, colors.HexColor("#94a3b8")),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]))

    story.append(table)
    story.append(Spacer(1, 20))

    # Disclaimer Note
    disclaimer_style = ParagraphStyle(
        "Disclaimer",
        parent=styles["Italic"],
        fontSize=8,
        leading=10,
        textColor=colors.HexColor("#64748b"),
    )
    story.append(Paragraph("Notice: Generated by NagrikLens for citizen guidance. Entitlements subject to statutory authority review.", disclaimer_style))

    doc.build(story)
    return buffer.getvalue()
